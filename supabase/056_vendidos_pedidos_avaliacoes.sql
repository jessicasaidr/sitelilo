-- 1) Vendidos: número aleatório entre 3 e 29 ---------------------------------
update public.products set sold = 3 + floor(random() * 27)::int;

-- 2) Pedidos -----------------------------------------------------------------
create table if not exists public.orders (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  items       jsonb not null,               -- [{ "id": 3, "name": "...", "variant": "...", "qty": 1, "price": 48.83 }]
  total       numeric(10,2),                -- cartão à vista
  pix_total   numeric(10,2),
  status      text not null default 'pendente'
              check (status in ('pendente', 'confirmado', 'enviado', 'entregue', 'cancelado')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders (user_id, created_at desc);

drop trigger if exists trg_orders_updated on public.orders;
create trigger trg_orders_updated before update on public.orders
for each row execute function public.set_updated_at();

alter table public.orders enable row level security;
drop policy if exists "pedidos: cliente cria"     on public.orders;
drop policy if exists "pedidos: cliente vê os seus" on public.orders;
drop policy if exists "pedidos: admin vê todos"   on public.orders;
drop policy if exists "pedidos: admin atualiza"   on public.orders;
drop policy if exists "pedidos: admin remove"     on public.orders;
create policy "pedidos: cliente cria"       on public.orders for insert to authenticated
  with check (user_id = auth.uid() and status = 'pendente');
create policy "pedidos: cliente vê os seus" on public.orders for select using (user_id = auth.uid());
create policy "pedidos: admin vê todos"     on public.orders for select using (public.is_admin());
create policy "pedidos: admin atualiza"     on public.orders for update using (public.is_admin()) with check (public.is_admin());
create policy "pedidos: admin remove"       on public.orders for delete using (public.is_admin());

-- 3) Avaliações ---------------------------------------------------------------
create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  product_id  bigint not null references public.products (id) on delete cascade,
  user_id     uuid not null default auth.uid() references auth.users (id) on delete cascade,
  nome        text not null,
  rating      int  not null check (rating between 1 and 5),
  comment     text check (char_length(comment) <= 1000),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (product_id, user_id)
);
create index if not exists reviews_product_idx on public.reviews (product_id, created_at desc);

drop trigger if exists trg_reviews_updated on public.reviews;
create trigger trg_reviews_updated before update on public.reviews
for each row execute function public.set_updated_at();

/* Pode avaliar? Precisa de um pedido confirmado/enviado/entregue com esse produto */
create or replace function public.can_review(pid bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.orders o
    where o.user_id = auth.uid()
      and o.status in ('confirmado', 'enviado', 'entregue')
      and o.items @> jsonb_build_array(jsonb_build_object('id', pid))
  );
$$;
grant execute on function public.can_review(bigint) to anon, authenticated;

alter table public.reviews enable row level security;
drop policy if exists "avaliações: todos leem"       on public.reviews;
drop policy if exists "avaliações: comprador cria"   on public.reviews;
drop policy if exists "avaliações: autor edita"      on public.reviews;
drop policy if exists "avaliações: autor/admin remove" on public.reviews;
create policy "avaliações: todos leem"     on public.reviews for select using (true);
create policy "avaliações: comprador cria" on public.reviews for insert to authenticated
  with check (user_id = auth.uid() and public.can_review(product_id));
create policy "avaliações: autor edita"    on public.reviews for update
  using (user_id = auth.uid()) with check (user_id = auth.uid() and public.can_review(product_id));
create policy "avaliações: autor/admin remove" on public.reviews for delete
  using (user_id = auth.uid() or public.is_admin());

/* Média e quantidade de avaliações por produto (para os cards e a página do produto) */
create or replace view public.product_ratings as
  select product_id, round(avg(rating)::numeric, 1) as avg, count(*)::int as total
  from public.reviews group by product_id;
grant select on public.product_ratings to anon, authenticated;

